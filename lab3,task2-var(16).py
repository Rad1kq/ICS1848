# значення для подальшоо обчислення середини відрізка
x1 = float(input("Введіть x1: "))
y1 = float(input("Введіть y1: "))
x2 = float(input("Введіть x2: "))
y2 = float(input("Введіть y2: "))
# формула для обчислення середини відрізка
middle_x = (x1 + x2) / 2
middle_y = (y1 + y2) / 2
# виведення координат середини відрізка
print(f"Координати середини відрізка: ({middle_x}, {middle_y})")

